//! Generate optional console-width tables from pinned local Unicode files.
const std = @import("std");
const unicode = @import("unicode.zig");
const Allocator = std.mem.Allocator;
const Range = [2]u21;

fn parse(gpa: Allocator, input: []const u8, properties: []const []const u8) !std.ArrayList(Range) {
    var result: std.ArrayList(Range) = .empty;
    errdefer result.deinit(gpa);
    var lines = std.mem.splitScalar(u8, input, '\n');
    while (lines.next()) |line| {
        const content = unicode.trim(line[0 .. std.mem.indexOfScalar(u8, line, '#') orelse line.len]);
        if (content.len == 0) continue;
        var fields = std.mem.splitScalar(u8, content, ';');
        const bounds = unicode.trim(fields.next().?);
        const property = unicode.trim(fields.next() orelse return error.InvalidUnicodeData);
        if (fields.next() != null) return error.InvalidUnicodeData;
        var selected = false;
        for (properties) |wanted| selected = selected or std.mem.eql(u8, property, wanted);
        if (!selected) continue;
        var endpoints = std.mem.splitSequence(u8, bounds, "..");
        const first = try unicode.codePoint(endpoints.next().?);
        const last = if (endpoints.next()) |end| try unicode.codePoint(end) else first;
        if (first > last or endpoints.next() != null) return error.InvalidUnicodeData;
        try result.append(gpa, .{ first, last });
    }
    return result;
}

fn merge(ranges: []Range) []Range {
    std.mem.sort(Range, ranges, {}, struct {
        fn less(_: void, a: Range, b: Range) bool {
            return a[0] < b[0];
        }
    }.less);
    var count: usize = 0;
    for (ranges) |range| {
        if (count != 0 and range[0] <= ranges[count - 1][1] + 1) {
            ranges[count - 1][1] = @max(ranges[count - 1][1], range[1]);
        } else {
            ranges[count] = range;
            count += 1;
        }
    }
    return ranges[0..count];
}

/// Verify merging against an independent membership map of the input ranges.
fn verifiedMerge(gpa: Allocator, ranges: []Range) ![]Range {
    const expected = try gpa.alloc(bool, 0x110000);
    defer gpa.free(expected);
    @memset(expected, false);
    for (ranges) |range| @memset(expected[range[0] .. @as(usize, range[1]) + 1], true);
    const merged = merge(ranges);
    var r: usize = 0;
    for (expected, 0..) |present, cp| {
        while (r < merged.len and cp > merged[r][1]) : (r += 1) {}
        if (present != (r < merged.len and cp >= merged[r][0])) return error.CompressionMismatch;
    }
    return merged;
}

fn emit(writer: *std.Io.Writer, name: []const u8, ranges: []const Range) !void {
    try writer.print("pub const {s} = [_][2]u21{{\n", .{name});
    for (ranges) |range| try writer.print("    .{{ 0x{x}, 0x{x} }},\n", .{ range[0], range[1] });
    try writer.writeAll("};\n\n");
}

pub fn main(init: std.process.Init) !void {
    const gpa = init.arena.allocator();
    const args = try init.minimal.args.toSlice(gpa);
    const check = unicode.checkPath(args, 3) catch |err| {
        std.debug.print("usage: generate-console-widths EastAsianWidth.txt DerivedGeneralCategory.txt UNICODE_LICENSE.txt [--check output.zig]\n", .{});
        return err;
    };
    const widths = try unicode.readPinned(gpa, init.io, args[1], unicode.east_asian_width);
    const categories = try unicode.readPinned(gpa, init.io, args[2], unicode.general_category);
    const license = try unicode.readPinned(gpa, init.io, args[3], unicode.license);
    const wide = try parse(gpa, widths, &.{ "W", "F" });
    var zero = try parse(gpa, categories, &.{ "Mn", "Me" });
    try zero.appendSlice(gpa, &.{ .{ 0x1160, 0x11ff }, .{ 0xd7b0, 0xd7ff } });
    const control = try parse(gpa, categories, &.{ "Cc", "Cf", "Zl", "Zp" });
    var buffer: std.Io.Writer.Allocating = .init(gpa);
    const writer = &buffer.writer;
    try writer.writeAll("//! Generated by tools/generate_console_widths.zig from Unicode 17.0.0.\n//! Used only by optional console presentation, never by either parser.\n");
    var lines = std.mem.splitScalar(u8, std.mem.trimEnd(u8, license, "\n"), '\n');
    while (lines.next()) |line| {
        if (line.len == 0) try writer.writeAll("//\n") else try writer.print("// {s}\n", .{line});
    }
    try writer.print("// EastAsianWidth.txt SHA-256: {s}\n// extracted/DerivedGeneralCategory.txt SHA-256: {s}\n\n", .{ unicode.east_asian_width.sha256, unicode.general_category.sha256 });
    try emit(writer, "wide", try verifiedMerge(gpa, wide.items));
    try emit(writer, "zero", try verifiedMerge(gpa, zero.items));
    try emit(writer, "control", try verifiedMerge(gpa, control.items));
    try unicode.output(gpa, init.io, buffer.written(), check);
}

test "property parsing and merging preserve holes, overlaps and the last code point" {
    const gpa = std.testing.allocator;
    var ranges = try parse(gpa, "# test\n0005..0007 ; W # selected\n0001 ; F\n0002..0005 ; W\n0008 ; Na\n10FFFF ; F\n0003 ; W\n", &.{ "W", "F" });
    defer ranges.deinit(gpa);
    const merged = try verifiedMerge(gpa, ranges.items);
    try std.testing.expectEqualSlices(Range, &.{ .{ 1, 7 }, .{ 0x10ffff, 0x10ffff } }, merged);
    var empty: [0]Range = .{};
    try std.testing.expectEqual(@as(usize, 0), (try verifiedMerge(gpa, &empty)).len);
}

test "malformed ranges are rejected" {
    const gpa = std.testing.allocator;
    try std.testing.expectError(error.InvalidUnicodeData, parse(gpa, "0002..0001;W", &.{"W"}));
    try std.testing.expectError(error.InvalidUnicodeData, parse(gpa, "110000;W", &.{"W"}));
    try std.testing.expectError(error.InvalidUnicodeData, parse(gpa, "0001;W;extra", &.{"W"}));
}
